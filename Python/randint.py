#generating random integers using randint() function

import random

random_int = random.randint(1, 100)

print(f"Random integer generted between 1 and 100: {random_int}")


rand_float = random.uniform(1, 100)

print(f"Random float between 1 and 100: {rand_float}")

rand_uniform = random.uniform(0, 1)

print(f"Random number between 0 and 1: {rand_uniform}")

random_random = random.random()

print(f"Random number between 0 and 1: {random_random}")

